import fs from 'node:fs/promises';
import {base,ready} from './browser.mjs';
export async function runInteractions(page,output) {
 const checks=[];
 const record=(id,pass,detail)=>{checks.push({id,pass:!!pass,detail});console.log(id,!!pass)};
 const observe=async()=>{await page.snapshot()};
 const focusBoundary=async(selector,last)=>page.evaluate(({selector,last})=>{const box=document.querySelector(selector); const items=[...box.querySelectorAll('a[href],button,input,select,textarea,[tabindex="0"]')].filter(e=>!e.disabled&&e.getClientRects().length);(last?items.at(-1):items[0])?.focus()}, {selector,last});
 const inside=async(selector)=>page.evaluate(selector=>!!document.querySelector(selector)?.contains(document.activeElement),selector);
 await page.cdp('Emulation.setDeviceMetricsOverride',{width:375,height:812,deviceScaleFactor:1,mobile:false});
 await page.goto(base+'/');await ready(page);await observe();
 await page.click('button[aria-label="메뉴 열기"]');await observe();
 record('menu-dialog',await page.evaluate(()=>!!document.querySelector('[role="dialog"][aria-modal="true"]')));
 record('menu-initial-focus',await inside('[data-theme-surface="dark"]:not(.lg\\:flex):not(header)'));
 record('menu-scroll-lock',await page.evaluate(()=>getComputedStyle(document.body).overflow==='hidden'));
 const menu='div.fixed.inset-0 > aside';
 await focusBoundary(menu,true);await page.keyboard.press('Tab');record('menu-forward-trap',await inside(menu));
 await focusBoundary(menu,false);await page.keyboard.press('Shift+Tab');record('menu-reverse-trap',await inside(menu));
 await page.keyboard.press('Escape');
 record('menu-escape',await page.evaluate(()=>!document.querySelector('button[aria-label="메뉴 닫기"]')));
 record('menu-restore-focus',await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')==='메뉴 열기'));
 if(await page.evaluate(()=>!!document.querySelector('button[aria-label="메뉴 닫기"]'))) await page.click('button[aria-label="메뉴 닫기"]');
 await page.cdp('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
 await page.goto(base+'/settings');await ready(page);await observe();
 await page.click('loc=role:button[name="측정 기본값 되돌리기"]');await observe();
 record('confirm-initial-focus',await page.evaluate(()=>document.activeElement?.textContent==='취소'));
 record('confirm-scroll-lock',await page.evaluate(()=>getComputedStyle(document.body).overflow==='hidden'));
 await focusBoundary('[role=alertdialog]',true);await page.keyboard.press('Tab');record('confirm-forward-trap',await inside('[role=alertdialog]'));
 await focusBoundary('[role=alertdialog]',false);await page.keyboard.press('Shift+Tab');record('confirm-reverse-trap',await inside('[role=alertdialog]'));
 await page.keyboard.press('Escape');record('confirm-escape',await page.evaluate(()=>!document.querySelector('[role=alertdialog]')));
 record('confirm-restore-focus',await page.evaluate(()=>document.activeElement?.textContent?.includes('측정 기본값 되돌리기')));
 await page.click('loc=role:button[name="프로젝트 관리"]');await observe();
 record('drawer-initial-focus',await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')==='상세 닫기'));
 record('drawer-scroll-lock',await page.evaluate(()=>getComputedStyle(document.body).overflow==='hidden'));
 await focusBoundary('[role=dialog]',true);await page.keyboard.press('Tab');record('drawer-forward-trap',await inside('[role=dialog]'));
 await focusBoundary('[role=dialog]',false);await page.keyboard.press('Shift+Tab');record('drawer-reverse-trap',await inside('[role=dialog]'));
 await page.keyboard.press('Escape');record('drawer-escape',await page.evaluate(()=>!document.querySelector('[role=dialog]')));
 record('drawer-restore-focus',await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')==='프로젝트 관리'));
 await page.click('loc=role:button[name="설정 저장"]');await page.waitForFunction(()=>document.querySelector('main')?.innerText.includes('전역 설정이 안전하게 저장되었습니다.'));
 record('settings-save',true);
 record('settings-save-announced',await page.evaluate(()=>[...document.querySelectorAll('[role=status],[aria-live=polite]')].some(e=>e.textContent.includes('전역 설정이 안전하게 저장되었습니다.'))));
 await page.goto(base+'/llms');await ready(page);await observe();
 await page.fill('input[type=url]','https://example.com');
 await page.click('loc=role:button[name="초안 생성"]');await page.waitForSelector('textarea[aria-label="llms.txt 내용"]');
 record('llms-generate',await page.evaluate(()=>document.querySelector('textarea[aria-label="llms.txt 내용"]').value.startsWith('# ')));
 await page.click('loc=role:button[name="검증"]');await page.waitForFunction(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='검증')?.disabled===false);
 record('llms-validate',await page.evaluate(()=>document.querySelector('main').innerText.includes('배포 가능')));
 await page.goto(base+'/learn');await ready(page);await page.waitForSelector('input[placeholder="실행 메모"]');await observe();
 const memo='input[placeholder="실행 메모"] >> nth=0';
 const oldMemo=await page.evaluate(()=>document.querySelector('input[placeholder="실행 메모"]').value);
 await page.fill(memo,'frontend-rsi memo');await page.press(memo,'Tab');
 await page.waitForFunction(async()=>{const r=await fetch('/api/checklist');const d=await r.json();return d.checklist.items.some(i=>i.note==='frontend-rsi memo')});
 record('memo-save',true);await page.fill(memo,oldMemo);await page.press(memo,'Tab');
 await page.goto(base+'/workspace');await ready(page);await observe();
 const backupInput=await page.evaluate(()=>[...document.querySelectorAll('main input')].find(e=>e.value==='로컬 백업')?.outerHTML);
 await page.fill('main input[maxlength="120"] >> nth=0','RSI test backup');
 await page.click('loc=role:button[name="백업 생성"]');await page.waitForFunction(()=>document.querySelector('main').innerText.includes('로컬 백업을 만들었습니다.'));
 record('backup-create',true,backupInput);
 await observe();
 await page.click('button:text-is("이름 변경") >> nth=0');
 await observe();
 await page.fill('main input[maxlength="120"] >> nth=1','RSI renamed backup');
 await page.press('main input[maxlength="120"] >> nth=1','Enter');
 let enterSaved=true;
 try { await page.waitForFunction(()=>document.querySelector('main').innerText.includes('백업 이름을 바꿨습니다.'),undefined,{timeout:2500}); } catch { enterSaved=false; }
 record('backup-rename-enter',enterSaved);
 if(!enterSaved) await page.click('button:text-is("저장")');
 await page.waitForFunction(()=>document.querySelector('main').innerText.includes('백업 이름을 바꿨습니다.'));
 record('backup-rename-save',true);
 await fs.writeFile(output,JSON.stringify(checks,null,2)+'\n');
 return checks;
}
